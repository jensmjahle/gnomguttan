import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../..', import.meta.url));
const app = path.join(root, 'gnomchat');
const { build } = await import(pathToFileURL(path.join(root, 'node_modules/vite/dist/node/index.js')).href);
const outDir = path.join(app, '.expo/matrix-engine-build');
await build({ configFile: false, root, resolve: { preserveSymlinks: true }, define: { 'process.env.NODE_ENV': '"production"' }, build: {
  outDir, emptyOutDir: true, target: 'es2022', minify: true, assetsInlineLimit: Number.MAX_SAFE_INTEGER,
  lib: { entry: path.join(app, 'matrix-engine/main.ts'), name: 'GnomMatrixEngine', formats: ['iife'], fileName: () => 'engine.js' },
  rollupOptions: { output: { inlineDynamicImports: true } },
} });
const files = await readdir(outDir);
if (files.some(file => file.endsWith('.wasm'))) throw new Error('Matrix engine must inline its WASM asset.');
const script = (await readFile(path.join(outDir, 'engine.js'), 'utf8')).replace(/<\/script/gi, '<\\/script');
const html = '<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"></head><body><script>window.addEventListener("error",function(e){window.ReactNativeWebView&&window.ReactNativeWebView.postMessage(JSON.stringify({type:"error",error:e.message||"Matrix kunne ikke starte."}));});</script><script>' + script + '</script></body></html>';
const generated = path.join(app, 'src/generated');
await mkdir(generated, { recursive: true });
await writeFile(path.join(generated, 'matrixEngine.ts'), '// Generated by npm run build:matrix-engine. Local protocol/crypto worker; no website UI.\nexport const MATRIX_ENGINE_HTML = ' + JSON.stringify(html) + ';\n');
console.log('Local Matrix engine generated.');
